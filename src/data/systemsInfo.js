// ── System specs synthesizer ────────────────────────────────────────────────
// Deterministically derive General/Device-type/Coverage fields per system id
// for the Info tab. Real product would store these on the system record;
// for the mockup we pick from small pools indexed by a stable hash.
function _hash(s) {
  let h = 0;
  for (let i = 0; i < (s || '').length; i++) { h = ((h << 5) - h) + s.charCodeAt(i); h |= 0; }
  return Math.abs(h);
}
const PIPE_TOPOLOGIES = ['Closed loop', 'Open loop', 'Recirculating'];
const VALVE_MODELS   = ['Belimo XYZ 2"', 'Belimo PR 3"', 'Honeywell V4297A 2"', 'Siemens SAS-31 2"'];
const METER_MODELS   = ['Arad Octave 2"', 'Arad Octave 3"', 'Sensus iPERL 1.5"', 'Itron Aquadis+ 2"'];
const ENV_BY_PREFIX = [
  { re: /(^|_)ct/,  v: 'HVAC chilled cold water loop' },
  { re: /(^|_)sp/,  v: 'Domestic cold water · sump' },
  { re: /(^|_)dhw/, v: 'Domestic hot water loop' },
  { re: /(^|_)dcw/, v: 'Domestic cold water loop' },
  { re: /(^|_)ms/,  v: 'Main supply line' },
  { re: /(^|_)f\d+/, v: 'Floor riser · cold + hot water' },
  { re: /(^|_)br/,  v: 'Boiler room · main feed' },
  { re: /tidhar_apt/, v: 'Apartment domestic supply' },
  { re: /dl_apt/,   v: 'Apartment domestic supply' },
];
const DEVICE_FAMILIES = ['WINT3 VMA', 'WINT3 VMA', 'WINT3 VMA', 'Flowless']; // WINT3 weighted

export function getSystemSpecs(systemId) {
  const h = _hash(systemId);
  const env = ENV_BY_PREFIX.find(e => e.re.test(systemId))?.v || 'General water supply';
  // Coverage area: 50–25,000 m². Tenant apartments are small (60–180); rest bigger.
  const isApt = /^(tidhar_apt|dl_apt)/.test(systemId);
  const coverageArea = isApt
    ? 60 + (h % 120)
    : 500 + (h % 25000);
  const occupancy = isApt
    ? 1 + (h % 6)
    : 20 + (h % 800);
  return {
    pipeTopology: PIPE_TOPOLOGIES[h % PIPE_TOPOLOGIES.length],
    valveModel: VALVE_MODELS[(h >> 3) % VALVE_MODELS.length],
    meterModel: METER_MODELS[(h >> 5) % METER_MODELS.length],
    monitoredEnvironment: env,
    deviceFamily: DEVICE_FAMILIES[(h >> 7) % DEVICE_FAMILIES.length],
    coverageArea,                 // m²
    occupancy,                    // people
  };
}
